/// Host OS metrics gathered by the Client Daemon using `sysinfo`.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SystemTelemetry {
    /// Overall CPU utilization percentage (0.0 - 100.0)
    pub cpu_usage_pct: f32,
    /// Memory used in megabytes
    pub ram_used_mb: u64,
    /// Total system RAM in megabytes
    pub ram_total_mb: u64,
    /// Disk space used in megabytes
    pub disk_used_mb: u64,
    /// Edge device GPU/CPU temperature in Celsius
    pub temperature_c: f32,
    /// Unix timestamp in seconds
    pub timestamp: u64,
}

/// A reading from a physical or simulated edge sensor.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SensorReading {
    /// Unique identifier for the sensor (e.g., "gpu_temp_probe_01")
    pub sensor_id: String,
    /// The metric being measured (e.g., "edge_gpu_temp")
    pub metric: String,
    /// The numeric value recorded
    pub value: f64,
    /// Unix timestamp in seconds
    pub timestamp: u64,
}

/// Alert payload generated when a WASM microservice detects an anomaly.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AnomalyAlert {
    /// Name of the metric that breached threshold
    pub metric: String,
    /// Recorded value that triggered the alert
    pub recorded_value: f64,
    /// Defined safety threshold that was exceeded
    pub threshold: f64,
    /// Explanation of the anomaly
    pub reason: String,
    /// Timestamp of detection
    pub timestamp: u64,
}

/// Scalar environmental sensor telemetry (evaluated purely by WASM rules, no NN).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EnvironmentPayload {
    pub sensor_id: String,
    pub temperature_c: f64,
    pub humidity_pct: f64,
    pub voltage_v: f64,
    pub timestamp: u64,
}

/// Camera image or video frame payload for Computer Vision NN.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CameraFramePayload {
    pub camera_id: String,
    pub frame_id: u64,
    pub width: u32,
    pub height: u32,
    pub channels: u8,
    pub format: String, // e.g., "RGB8", "JPEG"
    pub motion_detected: bool,
    pub data_preview: Vec<u8>,
    pub timestamp: u64,
}

/// 3-Axis accelerometer vibration stream for Predictive Maintenance (1D-CNN).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct VibrationStreamPayload {
    pub sensor_id: String,
    pub sample_rate_hz: u32,
    pub axis_x: Vec<f32>,
    pub axis_y: Vec<f32>,
    pub axis_z: Vec<f32>,
    pub rms_velocity_mms: f32,
    pub timestamp: u64,
}

/// Acoustic microphone audio stream for Cavitation / Screech Anomaly Detection.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AudioStreamPayload {
    pub mic_id: String,
    pub sample_rate_hz: u32,
    pub sound_pressure_db: f32,
    pub mel_spectrum: Vec<f32>,
    pub timestamp: u64,
}

