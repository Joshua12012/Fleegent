/// Target sensor modality for an AI model
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum Modality {
    /// Computer Vision: defect classification, object detection (MobileNet, YOLO)
    Vision,
    /// 3-Axis Accelerometer waveform analysis for predictive maintenance (1D-CNN)
    Vibration,
    /// Acoustic anomaly detection, frequency spectrum analysis
    Audio,
    /// Natural language diagnostic reasoning, log analysis (SmolLM, Qwen)
    #[default]
    Text,
}

/// Catalog entry for models available to deploy from the Cloud Server
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ModelCatalogItem {
    pub model_id: String,
    pub name: String,
    pub modality: Modality,
    pub size_mb: f32,
    pub format: String,
    pub description: String,
    pub download_url: String,
    pub sha256: String,
}

