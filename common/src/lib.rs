/// Generic request submitted to the AI Inference Worker.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct InferenceRequest {
    /// Unique identifier to correlate requests with responses
    pub request_id: String,
    /// The natural language or prompt payload for the AI model
    pub prompt: String,
    /// The target model engine (e.g., "qwen-1.5b", "mock-diagnostic")
    pub model_target: String,
    /// Maximum new tokens to generate
    pub max_tokens: usize,
    /// Timestamp of the request
    pub timestamp: u64,
}

/// Typed request for Computer Vision (Images / Video).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct VisionInferenceRequest {
    pub request_id: String,
    pub camera_frame: CameraFramePayload,
    pub model_target: String,
    pub timestamp: u64,
}

/// Typed request for 3-Axis Accelerometer Vibration (Predictive Maintenance).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct VibrationInferenceRequest {
    pub request_id: String,
    pub vibration: VibrationStreamPayload,
    pub model_target: String,
    pub timestamp: u64,
}

/// Typed request for Acoustic Audio Anomaly Detection.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AudioInferenceRequest {
    pub request_id: String,
    pub audio: AudioStreamPayload,
    pub model_target: String,
    pub timestamp: u64,
}

/// Result returned by the AI Inference Worker.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct InferenceResponse {
    /// Correlated request ID
    pub request_id: String,
    /// The text diagnosis or generated completion
    pub output_text: String,
    /// Total number of tokens generated
    pub tokens_generated: usize,
    /// Inference latency in milliseconds
    pub latency_ms: u64,
    /// The active backend that generated the result ("mock" or "llama_cpp" or "tensorrt")
    pub backend: String,
    /// Timestamp of completion
    pub timestamp: u64,
    /// Structured Vision results if modality was Vision
    #[serde(default)]
    pub vision_result: Option<VisionInferenceResult>,
    /// Structured Vibration results if modality was Vibration
    #[serde(default)]
    pub vibration_result: Option<VibrationInferenceResult>,
    /// Structured Audio results if modality was Audio
    #[serde(default)]
    pub audio_result: Option<AudioInferenceResult>,
    /// Statistical model quality & drift tracking metrics
    #[serde(default)]
    pub drift_metrics: Option<ModelDriftMetrics>,
}

/// Real-time statistical model drift & quality metrics calculated from sliding windows.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ModelDriftMetrics {
    /// Running mean confidence score of recent detections (0.0 - 1.0)
    pub mean_confidence: f32,
    /// Variance / spread of detection confidence
    pub variance: f32,
    /// Whether drift is flagged (mean confidence dropped significantly below baseline)
    pub drift_detected: bool,
    /// Number of inference samples in rolling window
    pub sample_count: usize,
}

