/// Update target type for zero-downtime hot swapping
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub enum ReloadTarget {
    /// Update an AI model weights file (.gguf or .engine)
    Model,
    /// Update a CPU microservice WebAssembly binary (.wasm)
    WasmModule,
}

/// Command published to `admin.reload` to trigger a hot-swap.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ReloadCommand {
    /// Target type: Model or WasmModule
    pub target: ReloadTarget,
    /// Name or identifier of the component (e.g., "yolov8n", "qwen_model")
    pub component_id: String,
    /// The sensor modality this model executes (Vision, Vibration, Audio, Text)
    #[serde(default)]
    pub modality: Modality,
    /// Human-friendly display name
    #[serde(default)]
    pub model_name: String,
    /// Absolute path to the newly staged file on local disk
    pub file_path: String,
    /// SHA-256 checksum to verify file integrity
    pub sha256_checksum: String,
    /// Unix timestamp of the command
    pub timestamp: u64,
    /// Optional deployment tracking ID from Cloud Control Plane
    #[serde(default)]
    pub deployment_id: Option<String>,
}

/// Health and readiness status reported by workers during normal operation or probation.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct HealthReport {
    /// Name of the microservice reporting
    pub service: String,
    /// Current status: "READY", "PROBATION", "DEGRADED", or "FAILED"
    pub status: String,
    /// Active version tag (e.g., "v1.0.0", "v2.0.0")
    pub active_version: String,
    /// Uptime of this worker in seconds
    pub uptime_secs: u64,
    /// Error message if status is FAILED
    pub error_message: Option<String>,
    /// Timestamp of report
    pub timestamp: u64,
    /// Optional active deployment ID being acknowledged
    #[serde(default)]
    pub deployment_id: Option<String>,
}

