//! ==============================================================================
//! EDGE PLATFORM DEMO — COMMON IPC & MESSAGE SCHEMAS
//! ==============================================================================
//! This library defines the standard data contracts, NATS subjects, and serialization
//! schemas used across all client-side microservices on the edge device.
//!
//! Because all microservices communicate via local NATS IPC (127.0.0.1:4222), having
//! a shared definition ensures type safety and zero-friction data exchange.
//! ==============================================================================

use serde::{Deserialize, Serialize};

pub mod crypto;

// ==============================================================================
// 1. NATS IPC SUBJECT / TOPIC NAMESPACES
// ==============================================================================

/// Periodic OS-level device health metrics published by the Client Daemon
pub const TOPIC_TELEMETRY_SYSTEM: &str = "telemetry.system";

/// Raw sensor telemetry streams (generic/legacy)
pub const TOPIC_TELEMETRY_SENSOR: &str = "telemetry.sensor";

/// Multi-modal sensor streams
pub const TOPIC_SENSOR_ENVIRONMENT: &str = "sensor.environment";
pub const TOPIC_SENSOR_CAMERA: &str = "sensor.camera";
pub const TOPIC_SENSOR_VIBRATION: &str = "sensor.vibration";
pub const TOPIC_SENSOR_AUDIO: &str = "sensor.audio";

/// High-priority alerts generated by the pure WASM microservices (e.g. overheating)
pub const TOPIC_TELEMETRY_ALERT: &str = "telemetry.alert";

/// AI inference request sent to the Inference Service (generic)
pub const TOPIC_INFERENCE_REQUEST: &str = "inference.request";

/// AI inference response containing generated tokens or diagnostic results
pub const TOPIC_INFERENCE_RESPONSE: &str = "inference.response";

/// Dedicated multi-modal inference request topics
pub const TOPIC_INFERENCE_VISION: &str = "inference.vision";
pub const TOPIC_INFERENCE_VIBRATION: &str = "inference.vibration";
pub const TOPIC_INFERENCE_AUDIO: &str = "inference.audio";
pub const TOPIC_INFERENCE_TEXT: &str = "inference.text";

/// Operational audit logs forwarded to the SQLite WAL storage service
pub const TOPIC_STORAGE_LOG: &str = "storage.log";

/// Administrative signals for zero-downtime hot reloading (Model or WASM updates)
pub const TOPIC_ADMIN_RELOAD: &str = "admin.reload";

/// Live device configuration updates (Azure-style modular services)
pub const TOPIC_ADMIN_CONFIG: &str = "admin.config";

/// Health heartbeats and probation check reports sent to the Client Daemon
pub const TOPIC_ADMIN_HEALTH: &str = "admin.health";

